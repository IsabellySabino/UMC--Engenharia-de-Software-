dia = float(input("Insira um número de 1 a 7: "))

if dia == 1:
    print ("1 - Segunda - feira")

elif dia == 2:
    print("2 - Terça - feira")

elif dia == 3:
    print("3 - Quarta - feira")

elif dia == 4:
    print("4 - Quinta - feira")

elif dia == 5:
    print("5 - Sexta - feira")

elif dia == 6:
    print("6 - Sábado - feira")
    
elif dia == 7:
    print("7 - Domingo - feira")

else:
    print("DIA INVÁLIDO")