# utilizei o comando for para definir quantas vezes o código será repetido 
for numeros in range(1,21):
    print(numeros)

# usei esse print() para pular linha entre as saídas do programa 
print()

# usei novamente o for para repetir a mesma equência de códigos, e o end para que os números sejam executados um ao lado do outro. 
for numeros in range(1,21):
    print(numeros, end=" ")